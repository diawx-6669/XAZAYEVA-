def _range_text(s: dict, root: dict) -> tuple[str, str]:
    if "$ref" in s:
        s = root["$defs"][s["$ref"].split("/")[-1]]
    if "oneOf" in s:
        parts = [_range_text(x, root) for x in s["oneOf"]]
        return " или ".join(p[0] for p in parts), " или ".join(p[1] for p in parts)
    t = s.get("type")
    if "enum" in s:
        return "enum", ", ".join(f"`{x}`" for x in s["enum"])
    if "const" in s:
        return "const", f"`{s['const']}`"
    if t == "array":
        it = s.get("items", {})
        if "$ref" in it:
            it = root["$defs"][it["$ref"].split("/")[-1]]
        it_t, it_r = _range_text(it, root)
        n = ""
        if s.get("minItems") == s.get("maxItems") == 2:
            n = "[мин, макс] "
        elif "minItems" in s:
            n = f"≥ {s['minItems']} элем. "
        return f"array of {it_t}", (n + it_r).strip()
    if t == "object":
        return "object", "ключи: " + ", ".join(f"`{k}`" for k in s.get("properties", {}))
    lo, hi = s.get("minimum"), s.get("maximum")
    r = ""
    if lo is not None and hi is not None:
        r = f"{lo}…{hi}"
    elif lo is not None:
        r = f"≥ {lo}"
    elif hi is not None:
        r = f"≤ {hi}"
    if "pattern" in s:
        r = "`" + s["pattern"].replace("|", "\\|") + "`"
    return t or "?", r or "любое"


def _default_text(v) -> str:
    txt = json.dumps(v, ensure_ascii=False, separators=(", ", ": "))
    return f"`{txt}`" if len(txt) <= 60 else f"`{txt[:57]}…`"


def render_reference() -> str:
    sch = _schema()
    props = sch["properties"]
    out = ["# Справочник параметров конфига", "",
           "Сгенерировано из `schemas/config.schema.json` и `auditenv/config.py::DEFAULT_CONFIG` командой",
           "`python -m auditenv validate-config --write-reference`; тест `tests/test_round4_config.py` сверяет файл со",
           "схемой. Конфиг — JSON с любым подмножеством ключей: недостающие берутся из значений по умолчанию",
           "(вложенные словари сливаются по ключам). Проверить свой файл:", "",
           "```bash", "python -m auditenv validate-config configs/dev-mixed.json", "```", "",
           "Что будет при выходе за диапазон: **конфиг не загрузится** — `load_config` бросает `ConfigError`,",
           "генератор не запускается, а `validate-config` печатает все нарушения сразу с подсказкой и кодом",
           "возврата 1. Неизвестный ключ — тоже ошибка (`additionalProperties: false`), чтобы опечатка не",
           "превращалась в молча проигнорированный параметр.", "",
           "| Параметр | Тип | Диапазон / значения | По умолчанию | Смысл |", "|---|---|---|---|---|"]
    for key, s in props.items():
        t, r = _range_text(s, sch)
        out.append(f"| `{key}` | {t} | {r} | {_default_text(DEFAULT_CONFIG.get(key))} | {MEANING.get(key, s.get('description', ''))} |")
        if s.get("type") == "object" or ("$ref" not in s and isinstance(s.get("properties"), dict)):
            for sub, ss in s.get("properties", {}).items():
                st, sr = _range_text(ss, sch)
                d = DEFAULT_CONFIG.get(key, {}).get(sub)
                out.append(f"| `{key}.{sub}` | {st} | {sr} | {_default_text(d) if d is not None else '— (0)'} | |")
    out += ["", "## Правила между параметрами (проверяются после схемы)", "",
            "| Где | Нарушение | Сообщение / причина |", "|---|---|---|"]
    out += [f"| {a} | {b} | {c} |" for a, b, c in CROSS_RULES]
    out += ["", "## Именованные конфиги", "", "| Файл | Версия | Отличия от значений по умолчанию |", "|---|---|---|"]
    for p in sorted((ROOT / "configs").glob("*.json")):
        raw = json.loads(p.read_text("utf-8"))
        if isinstance(raw, dict) and "name" in raw and "version" in raw:
            keys = ", ".join(f"`{k}`" for k in raw if k not in ("name", "version"))
            out.append(f"| `configs/{p.name}` | {raw['version']} | {keys or '—'} |")
    return "\n".join(out) + "\n"


def problems(path) -> list[str]:
    """All problems in a config file, each as one plain-language line (empty = valid)."""
    from .jsonschema_lite import Validator

    p = Path(path)
    if not p.exists():
        return [f"файл не найден: {p}"]
    try:
        raw = json.loads(p.read_text("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as e:
        return [f"не JSON: {e}"]
    if not isinstance(raw, dict):
        return ["конфиг должен быть JSON-объектом {...}"]
    cfg = _merge(DEFAULT_CONFIG, raw)
    sch = _schema()
    out = []
    for err in sorted(Validator(sch).iter_errors(cfg), key=lambda e: [str(x) for x in e.path]):
        key = err.path[0] if err.path else None
        hint = ""
        if key in sch["properties"]:
            t, r = _range_text(sch["properties"][key], sch)
            hint = f" (ожидается {t}: {r}; по умолчанию {_default_text(DEFAULT_CONFIG.get(key))})"
        elif err.validator == "additionalProperties":
            hint = " (опечатка? список ключей — docs/CONFIG_REFERENCE.md)"
        where = "/".join(str(x) for x in err.path) or "<корень>"
        out.append(f"{where}: {err.message}{hint}")
    if not out:
        try:
            validate_config(cfg)
        except ConfigError as e:
            out.append(str(e).split(": ", 1)[-1])
    return out


def main(argv) -> int:
    if "--write-reference" in argv:
        REF_PATH.write_text(render_reference(), "utf-8")
        print(f"validate-config: wrote {REF_PATH.relative_to(ROOT)}")
        return 0
    files = [a for a in argv if not a.startswith("--")]
    if not files:
        print("usage: python -m auditenv validate-config <config.json> [...]")
        return 2
    bad = 0
    for f in files:
        probs = problems(f)
        if probs:
            bad += 1
            print(f"{f}: НЕВЕРНЫЙ КОНФИГ, {len(probs)} проблем(ы):")
            for x in probs:
                print(f"  - {x}")
        else:
            print(f"{f}: OK")
    return 1 if bad else 0
