"""Benford check: how realistic are the amounts, and do injected errors change the digit pattern?

Two questions, answered on generated episodes of every open config:

1. Realism. First-digit distribution of unit prices, invoice totals and base-currency ledger amounts vs
   Benford's law, scored by the mean absolute deviation (MAD) with Nigrini's first-digit bands:
   <= 0.006 close, <= 0.012 acceptable, <= 0.015 marginal, > 0.015 nonconformity.
2. Shortcut. The same MAD for ledger rows that post an affected document vs clean rows, and the distance
   between those two distributions. A Benford test is a real audit technique; if injected errors moved the
   digits, it would find them without any reconciliation - a shortcut. They should look alike.

    python tools/benford.py [--n 100]    # writes reports/benford.md (make benford)
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from auditenv.config import load_config  # noqa: E402
from auditenv.env.data import PublicData  # noqa: E402
from auditenv.generator.episode import generate_episode  # noqa: E402

CONFIGS = ("train-easy", "dev-mixed", "interaction-heavy", "train-global", "dev-global")
BENFORD = [math.log10(1 + 1 / d) for d in range(1, 10)]
GROUPS = ("unit prices", "invoice totals", "ledger amounts (base)", "ledger: clean rows",
          "ledger: rows of affected documents")


def first_digit(n: int):
    n = abs(int(n))
    if n == 0:
        return None
    while n >= 10:
        n //= 10
    return n


def distribution(values):
    counts = [0] * 9
    for v in values:
        d = first_digit(v)
        if d:
            counts[d - 1] += 1
    total = sum(counts) or 1
    return [c / total for c in counts], sum(counts)


def mad(p, q=BENFORD):
    return sum(abs(a - b) for a, b in zip(p, q)) / 9


def band(m):
    return "close" if m <= 0.006 else "acceptable" if m <= 0.012 else "marginal" if m <= 0.015 else "nonconformity"


def collect(n):
    groups = {"unit prices": [], "invoice totals": [], "ledger amounts (base)": [], "ledger: clean rows": [],
              "ledger: rows of affected documents": []}
    for cname in CONFIGS:
        cfg = load_config(cname)
        for s in range(900000, 900000 + n):
            ep = generate_episode(s, cfg)
            d = PublicData(ep.files)
            affected = {a for i in ep.truth["issues"] for a in i["affected_ids"]}
            for inv in d.invoices:
                groups["invoice totals"].append(inv["total_minor"])
                groups["unit prices"] += [li["unit_price_minor"] for li in inv["line_items"]]
            for r in d.ledger:
                amt = int(r["debit_minor"] or 0) or int(r["credit_minor"] or 0)
                groups["ledger amounts (base)"].append(amt)
                hit = r.get("invoice_id") in affected or r.get("payment_id") in affected
                groups["ledger: rows of affected documents" if hit else "ledger: clean rows"].append(amt)
    return groups


def run(n=100):
    out = {}
    for name, vals in collect(n).items():
        p, count = distribution(vals)
        out[name] = {"n": count, "dist": p, "mad": mad(p)}
    gap = mad(out["ledger: rows of affected documents"]["dist"], out["ledger: clean rows"]["dist"])
    return {"n_seeds": n, "configs": list(CONFIGS), "groups": out, "affected_vs_clean_mad": gap}


def render(r) -> str:
    g = r["groups"]
    lines = [
        "# Benford check: realism of amounts and a possible shortcut",
        "",
        "Generated by `python tools/benford.py` (`make benford`), deterministic: "
        f"{r['n_seeds']} seeds x {len(r['configs'])} configs ({', '.join(r['configs'])}).",
        "",
        "MAD = mean absolute deviation of first-digit shares from Benford; bands after Nigrini "
        "(first digit): <= 0.006 close, <= 0.012 acceptable, <= 0.015 marginal, > 0.015 nonconformity.",
        "",
        "| Amounts | n | MAD vs Benford | band | " + " | ".join(str(d) for d in range(1, 10)) + " |",
        "|---|---|---|---|" + "---|" * 9,
        "| Benford | | | | " + " | ".join(f"{b:.3f}" for b in BENFORD) + " |",
    ]
    for name in GROUPS:
        v = g[name]
        lines.append(f"| {name} | {v['n']} | {v['mad']:.4f} | {band(v['mad'])} | "
                     + " | ".join(f"{x:.3f}" for x in v["dist"]) + " |")
    gap = r["affected_vs_clean_mad"]
    lines += [
        "",
        "## What it means",
        "",
        f"1. **Realism (honest limitation).** Unit prices are drawn uniformly from a per-currency range "
        f"(`price()` in `auditenv/generator/story.py`), so their first digits follow the ranges, not Benford "
        f"(MAD {g['unit prices']['mad']:.4f}, {band(g['unit prices']['mad'])}). Quantities, sums of several "
        f"lines and currency conversion mix the digits: invoice totals MAD {g['invoice totals']['mad']:.4f} "
        f"({band(g['invoice totals']['mad'])}), the ledger as a whole {g['ledger amounts (base)']['mad']:.4f} "
        f"({band(g['ledger amounts (base)']['mad'])}). Real receivables often do not follow Benford either when "
        "prices sit in a narrow band, so this is a realism note, not a bug. A log-uniform price draw would "
        "make the books Benford-like; it changes every episode byte, so it is listed in `docs/ROADMAP.md`.",
        f"2. **No shortcut.** Rows of affected documents and clean rows have nearly the same digit pattern: "
        f"MAD between them {gap:.4f}. Errors are injected by copying or re-posting real amounts, so a Benford "
        "test cannot point at them - the agent has to reconcile.",
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=100)
    a = ap.parse_args(argv)
    r = run(a.n)
    (ROOT / "reports" / "benford.md").write_text(render(r), "utf-8")
    (ROOT / "reports" / "benford.json").write_text(json.dumps(r, sort_keys=True, indent=1) + "\n", "utf-8")
    print(f"benford: unit prices MAD {r['groups']['unit prices']['mad']:.4f}, ledger "
          f"{r['groups']['ledger amounts (base)']['mad']:.4f}, affected vs clean {r['affected_vs_clean_mad']:.4f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
