"""A15: tool definitions for LLM agents, generated from schemas/action.schema.json (+ findings schema).

    python tools/llm/build.py      -> tools/llm/{openai_tools.json, anthropic_tools.json, system_prompt.md,
                                                  fewshot_erroneous.json, fewshot_clean.json}

* openai_tools.json    - Chat Completions / Responses "function" tools ({"type": "function", "function": {...}});
* anthropic_tools.json - Messages API tools ({"name", "description", "input_schema"});
  the parameter schemas are exactly the `args` branches of the action schema, $ref inlined;
* system_prompt.md     - the task text the env itself gives (env.task_text) + the protocol of a tool call;
* fewshot_*.json       - two transcripts recorded from `oracle_observing` on OPEN dev episodes: one with
  errors, one clean. Observations are what the env returned (no answer key: checked by leakscan in
  tests/test_round4_llm.py); the final submit is the correct answer for that open episode.
No network, no API keys: these are files to paste into an agent harness.
"""

from __future__ import annotations

import copy
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
OUT = Path(__file__).resolve().parent
FEWSHOT = {"fewshot_erroneous.json": "ep-vw9vceq4qf", "fewshot_clean.json": "ep-eedmc2zyem"}

EXPLAIN = {
    "fx_rate": "Posted with the rate of another date than the policy's local transaction date; "
               "amount = |posted base amount - amount at the correct fx row|.",
    "payment_allocation": "Receipt references the invoice but part of it was credited to 2400 Unapplied Cash "
                          "instead of 1200; amount = the part left on 2400.",
    "duplicate_invoice": "Same customer and identical line items as an earlier invoice, both posted; "
                         "amount = the duplicate's 1200 debit.",
    "period_cutoff": "Issued outside the period by the company's local time but posted inside it; "
                     "amount = the invoice's base amount.",
}

DESCRIPTIONS = {
    "list_records": "List one page (at most 50 rows) of a public table. Pass next_cursor from the previous "
                    "page to continue; cursors are opaque and valid only in this episode.",
    "get_record": "Get one record by its ID: ledger row_id, invoice_id, payment_id, an fx id "
                  "'fx:DATE:SRC:TGT', or table='policy' with id='policy' for the accounting policy.",
    "get_document": "Get one invoice or payment document by its doc_id.",
    "calculator": "Exact decimal arithmetic: numbers, + - * /, unary minus and parentheses only "
                  "(no names, calls or powers; at most 200 characters).",
    "submit": "Submit all findings and END the episode. An empty findings list is correct for clean books. "
              "A malformed submission ends the episode with reward -1.",
}


def _schemas():
    s = lambda n: json.loads((ROOT / "schemas" / n).read_text("utf-8"))  # noqa: E731
    return s("action.schema.json"), s("findings.schema.json")


def _inline(node, findings):
    if isinstance(node, dict):
        if node.get("$ref") == "findings.schema.json":
            f = copy.deepcopy(findings)
            for k in ("$schema", "$id", "title"):
                f.pop(k, None)
            return f
        return {k: _inline(v, findings) for k, v in node.items()}
    if isinstance(node, list):
        return [_inline(x, findings) for x in node]
    return node


def tool_params() -> dict:
    action, findings = _schemas()
    out = {}
    for branch in action["oneOf"]:
        name = branch["properties"]["tool"]["const"]
        out[name] = _inline(branch["properties"]["args"], findings)
    assert list(out) == action["properties"]["tool"]["enum"]
    return out


def openai_tools() -> list:
    return [{"type": "function", "function": {"name": n, "description": DESCRIPTIONS[n], "parameters": p}}
            for n, p in tool_params().items()]


def anthropic_tools() -> list:
    return [{"name": n, "description": DESCRIPTIONS[n], "input_schema": p} for n, p in tool_params().items()]


def system_prompt() -> str:
    from auditenv.env.env import task_text

    return ("# System prompt for an LLM auditor in AuditEnv\n\n"
            "Generated by `python tools/llm/build.py` from `auditenv/env/env.py::task_text` (the env gives the same "
            "text in the first observation, field `task`).\n\n```text\n" + task_text() + "\n\n"
            "Protocol: call exactly one tool per turn. The tool result is the env observation: "
            "{result | error, steps_remaining}. Errors are bare codes (unknown_tool, bad_args, not_found, "
            "invalid_cursor, calc_error, episode_over) and still cost a step. Read the policy record first "
            "(get_record table=policy id=policy). Prove every finding with one complete evidence set: the "
            "documents, the ledger rows and, for FX and cut-off, the fx row and 'policy'. Finish with submit.\n```\n")


def fewshot(episode_id: str) -> dict:
    from auditenv.runner import run_episode

    d = next(p for p in (ROOT / "episodes").glob(f"*/{episode_id}"))
    r = run_episode("oracle_observing", episode_dir=str(d), isolate=False)
    msgs = []
    for rec in r["trajectory"]:
        if rec["action"] is not None:
            args = copy.deepcopy(rec["action"].get("args", {}))
            for f in (args.get("findings") or {}).get("findings", []):
                f["explanation"] = EXPLAIN[f["type"]]  # the recorded "oracle"; explanation never affects reward
            msgs.append({"role": "assistant", "tool": rec["action"]["tool"], "args": args})
        msgs.append({"role": "env", "observation": rec["observation"], "step": rec["step"]})
    return {"episode_id": r["grade"]["episode_id"], "source": f"episodes/{d.parent.name}/{episode_id}",
            "policy": "oracle_observing", "reward": r["grade"]["reward"], "steps": r["grade"]["steps"],
            "note": "recorded transcript on an OPEN episode; observations contain no answer key (leakscan); "
                    "only the explanation texts were rewritten (they never affect the reward)",
            "messages": msgs}


def build() -> dict:
    files = {"openai_tools.json": openai_tools(), "anthropic_tools.json": anthropic_tools()}
    files.update({name: fewshot(eid) for name, eid in FEWSHOT.items()})
    out = {k: json.dumps(v, indent=1, ensure_ascii=False, sort_keys=True) + "\n" for k, v in files.items()}
    out["system_prompt.md"] = system_prompt()
    return out


if __name__ == "__main__":
    for name, text in build().items():
        (OUT / name).write_text(text, "utf-8")
        print(f"llm: wrote tools/llm/{name}")
